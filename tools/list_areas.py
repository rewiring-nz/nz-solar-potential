"""Write the national LINZ locality catalogue without fetching building outlines.

    .venv/bin/python tools/list_areas.py

Refreshes docs/data-maintainers/areas.md. Needs a LINZ key; starts no builds.
"""

import argparse
from collections import Counter, defaultdict
from datetime import date
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src import localities as L  # noqa: E402
from src.project_secrets import linz_api_key  # noqa: E402

OUTPUT = ROOT / "docs" / "data-maintainers" / "areas.md"
WATER_TYPES = {"Lake", "Inland Bay"}


def cell(value: str) -> str:
    return value.replace("|", r"\|").replace("\n", " ").replace("\r", " ")


def render(localities: list[dict], retrieved: str) -> str:
    if not localities:
        raise ValueError("Cannot generate a national catalogue from an empty response")
    ambiguous = L.ambiguous_ids(localities)
    included = [p for p in localities if p.get("type") not in WATER_TYPES]
    if not included:
        raise ValueError("Catalogue has no candidate areas")
    groups = defaultdict(list)
    for p in included:
        council = L.territorial_authorities(p)[0]
        groups[council].append(p)
    ids = [L.display_region_id(p, ambiguous) for p in included]
    if len(set(ids)) != len(ids):
        raise ValueError("Catalogue contains duplicate region ids")
    types = Counter(p["type"] for p in included)
    lines = [
        "# Areas",
        "",
        "National candidate areas under the definition in [Choosing an area](choosing-an-area.md).",
        "One row is one LINZ suburb or locality feature, not a bounding-box grid cell.",
        "",
        f"Source: [LINZ NZ Suburbs and Localities, layer {L.config.LINZ_SUBURBS_LOCALITIES_LAYER}]"
        f"(https://data.linz.govt.nz/layer/{L.config.LINZ_SUBURBS_LOCALITIES_LAYER}-nz-suburbs-and-localities/).",
        f"Attributes retrieved {retrieved}: **{len(included):,} candidate areas**, grouped under",
        f"**{len(groups)} territorial-authority groups** (the first where LINZ lists several).",
        "The groups include LINZ's `Area outside Territorial Authority`, not just councils.",
        f"The source has {len(localities):,} features; {len(localities) - len(included):,} lakes and inland bays",
        "are excluded, matching the default area finder. Coastal bays, islands and",
        "conservation land remain candidates because they can contain buildings.",
        "",
        "**This is a coverage catalogue, not a build queue or a claim of readiness.**",
        "Building counts and survey coverage have not been checked here. Some candidates",
        "have no buildings; others need a configured survey before they can be built.",
        "Use `tools/find_area.py <name> --council <council> --details` to check a candidate",
        "before building. Legacy bounding-box regions are not part of this list.",
        "",
        "Region ids use the same helpers as the pipeline, including `no-town`,",
        "ASCII slugs and LINZ-id suffixes for name collisions. A multi-council",
        "feature appears once, under its first council; its other councils remain",
        "included when selecting buildings.",
        "",
        "Refresh from the repository root (LINZ key required; no building downloads",
        "or cloud builds):",
        "",
        "```sh",
        ".venv/bin/python tools/list_areas.py",
        "```",
        "",
        "Regeneration replaces this snapshot. Names and ids may change when LINZ",
        "updates the source. Generated by [tools/list_areas.py](../../tools/list_areas.py).",
        "",
        "## Area types",
        "",
        "| Type | Candidates |",
        "| --- | ---: |",
    ]
    lines += [f"| {cell(kind)} | {count:,} |" for kind, count in sorted(types.items())]
    lines += ["", "## Councils", "", "| Council | Candidates |", "| --- | ---: |"]
    lines += [f"| [{cell(council)}](#{L.slug(council)}) | {len(rows):,} |"
              for council, rows in sorted(groups.items())]
    for council, rows in sorted(groups.items()):
        lines += ["", f'<a id="{L.slug(council)}"></a>', "",
                  f"## {cell(council)}", "", f"{len(rows):,} candidate areas.", "",
                  "<details>", "<summary>Show areas and region ids</summary>", "",
                  "| Town / city | Area | Type | LINZ id | Region id |",
                  "| --- | --- | --- | ---: | --- |"]
        for p in sorted(rows, key=lambda p: (p.get("major_name") or "", p["name"], p["id"])):
            lines.append(
                f"| {cell(p.get('major_name') or 'No town / city')} | {cell(p['name'])} "
                f"| {cell(p['type'])} | {p['id']} | `{L.display_region_id(p, ambiguous)}` |")
        lines += ["", "</details>"]
    return "\n".join(lines) + "\n"


def main() -> int:
    argparse.ArgumentParser(description=__doc__).parse_args()
    key = linz_api_key()
    if not key:
        raise SystemExit("LINZ_API_KEY not set: see docs/data-maintainers/local-setup.md")
    try:
        features = L._wfs(key, L.config.LINZ_SUBURBS_LOCALITIES_LAYER, "INCLUDE",
                          L.LOCALITY_FIELDS)
    except L.requests.RequestException as exc:
        raise SystemExit(f"LINZ catalogue fetch failed ({type(exc).__name__}); "
                         "existing catalogue was not changed.") from None
    text = render([f["properties"] for f in features], date.today().isoformat())
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
